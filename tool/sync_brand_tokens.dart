import 'dart:io';

/// Copies the generated brand tokens from `design/` into the app.
///
/// The design generator writes `design/flutter/brand_tokens.dart`, the
/// single source of truth for colours, type, spacing and motion. This copies
/// it to `lib/design_system/tokens/brand_tokens.dart` with two changes: it
/// imports `material_ui` instead of the SDK's Material library, and it drops
/// the generator's sample `BrandTheme` (the app builds its own theme in
/// `lib/design_system/theme/`).
///
/// Run after regenerating the tokens: `dart run tool/sync_brand_tokens.dart`.
/// A test fails if the app copy is out of date.
void main() {
  final source = File('design/flutter/brand_tokens.dart').readAsStringSync();
  File(brandTokensTarget).writeAsStringSync(transformBrandTokens(source));
  stdout.writeln('Wrote $brandTokensTarget');
}

const brandTokensTarget = 'lib/design_system/tokens/brand_tokens.dart';

String transformBrandTokens(String source) {
  final trimmed = _removeClass(source, 'BrandTheme');
  final transformed = trimmed
      .replaceFirst(
        RegExp('^// GENERATED[^\n]*\n'),
        '// GENERATED by tool/sync_brand_tokens.dart from '
        'design/flutter/brand_tokens.dart.\n'
        '// Do not edit: change the design generator and re-sync.\n',
      )
      .replaceAll(
        "import 'package:flutter/material.dart';",
        "import 'package:material_ui/material_ui.dart';",
      )
      .trimRight()
      .replaceAll(RegExp(r'\n{3,}'), '\n\n');
  return '$transformed\n';
}

/// Removes `abstract final class [name] { … }` and the doc comment above it,
/// keeping everything before and after.
String _removeClass(String source, String name) {
  final start = source.indexOf('abstract final class $name');
  if (start < 0) return source;
  final open = source.indexOf('{', start);
  var depth = 0;
  var end = open;
  for (; end < source.length; end++) {
    if (source[end] == '{') depth++;
    if (source[end] == '}' && --depth == 0) break;
  }
  // Include the doc comment lines directly above the class.
  var docStart = start;
  final lines = source.substring(0, start).split('\n');
  // The last element is the (empty) remainder of the class's own line.
  for (var i = lines.length - 2; i >= 0 && lines[i].startsWith('///'); i--) {
    docStart -= lines[i].length + 1;
  }
  return source.substring(0, docStart) + source.substring(end + 1);
}

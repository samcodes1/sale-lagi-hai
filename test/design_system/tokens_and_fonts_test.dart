import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:sale_lagi_hai/design_system/fonts/font_licenses.dart';

// The sync tool lives outside lib/, so import it by path.
import '../../tool/sync_brand_tokens.dart';

/// Serves asset text from a map, for testing licence registration.
final class _MapBundle extends CachingAssetBundle {
  new(this.assets);

  final Map<String, String> assets;

  @override
  Future<ByteData> load(String key) async =>
      ByteData.sublistView(Uint8List.fromList(assets[key]!.codeUnits));

  @override
  Future<String> loadString(String key, {bool cache = true}) async =>
      assets[key]!;
}

void main() {
  group('brand tokens', () {
    test('the app copy is in sync with design/ '
        '(run: dart run tool/sync_brand_tokens.dart)', () {
      final source = File('design/flutter/brand_tokens.dart')
          .readAsStringSync();

      expect(
        File(brandTokensTarget).readAsStringSync(),
        transformBrandTokens(source),
      );
    });

    test('the transform switches to material_ui and drops BrandTheme', () {
      const source =
          '// GENERATED by x\n'
          "import 'package:flutter/material.dart';\n\n"
          'abstract final class BrandColors {}\n\n\n\n'
          '/// Sample theme.\n'
          'abstract final class BrandTheme {}\n';

      final out = transformBrandTokens(source);

      expect(out, contains("import 'package:material_ui/material_ui.dart';"));
      expect(out, isNot(contains('package:flutter/material.dart')));
      expect(out, isNot(contains('BrandTheme')));
      expect(out, isNot(contains('Sample theme')));
      expect(out, startsWith('// GENERATED by tool/sync_brand_tokens.dart'));
      expect(out, isNot(contains('\n\n\n')));
      expect(out, endsWith('{}\n'));
    });

    test('content after BrandTheme is kept, so drift there is caught', () {
      const source =
          "import 'package:flutter/material.dart';\n\n"
          'abstract final class BrandColors {}\n\n'
          '/// Sample theme.\n'
          'abstract final class BrandTheme {\n'
          '  static ThemeData light() { return ThemeData(); }\n'
          '}\n\n'
          'abstract final class BrandExtra { static const x = 1; }\n';

      final out = transformBrandTokens(source);

      expect(out, isNot(contains('BrandTheme')));
      expect(out, isNot(contains('ThemeData')));
      expect(out, contains('abstract final class BrandExtra'));
      expect(out, contains('abstract final class BrandColors'));
    });
  });

  group('bundled fonts', () {
    final pubspec = File('pubspec.yaml').readAsStringSync();
    final declared = RegExp(r'asset: (assets/fonts/\S+\.ttf)')
        .allMatches(pubspec)
        .map((m) => m[1]!)
        .toList();

    test('every declared font file exists', () {
      expect(declared, hasLength(10));
      for (final path in declared) {
        expect(File(path).existsSync(), isTrue, reason: path);
      }
    });

    test('the families match the names the tokens use', () {
      for (final family in [
        'BricolageCondensed',
        'BricolageGrotesque',
        'InstrumentSans',
        'NotoNastaliqUrdu',
        'NotoNaskhArabic',
      ]) {
        expect(pubspec, contains('- family: $family'), reason: family);
      }
    });

    test('every font has its licence file bundled', () {
      expect(pubspec, contains('- assets/fonts/licenses/'));
      for (final (_, path) in fontLicenses) {
        expect(File(path).existsSync(), isTrue, reason: path);
        expect(File(path).readAsStringSync(), contains('SIL Open Font'));
      }
    });

    test('fonts are never fetched at runtime', () {
      expect(pubspec, isNot(contains('google_fonts')));
    });
  });

  test('registerFontLicenses adds one OFL entry per font', () async {
    final bundle = _MapBundle({
      for (final (font, path) in fontLicenses) path: 'SIL Open Font $font',
    });

    registerFontLicenses(bundle: bundle);
    final entries = await LicenseRegistry.licenses.toList();
    final fontEntries = entries.where(
      (e) => e.packages.any((p) => fontLicenses.any((f) => f.$1 == p)),
    );

    expect(fontEntries.map((e) => e.packages.single).toSet(), {
      for (final (font, _) in fontLicenses) font,
    });
    expect(
      fontEntries.first.paragraphs.first.text,
      startsWith('SIL Open Font'),
    );
  });
}

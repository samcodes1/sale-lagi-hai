"""Builds every asset of the Naam Block logo. Usage: python build_naam.py

Needs fonttools, uharfbuzz, Pillow and Google Chrome. The logo is the full
name stacked as a 4x3 block, one colour on one colour. Geometry is on a 512
tile; the block stays inside the launcher safe circle (radius 234).

Writes Android icons, the welcome-screen logo, the Play Store icon and the
outlines the Flutter splash draws. Never hand-edit those outputs.
"""
import pathlib
import subprocess
import sys
import tempfile

import uharfbuzz as hb
from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[2]
FONT = ROOT / "design/fonts/static/BricolageGrotesqueCondensed-ExtraBold.ttf"
RES = ROOT / "android/app/src/main/res"
OUT = ROOT / "design/logo/naam-block"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"

RED = "#DC2E24"
WHITE = "#FFFFFF"

# The block on the 512 tile: three lines of equal size and width.
BLOCK_X, BLOCK_W, LINE_H, LINE_GAP = 106, 300, 104, 13
BLOCK_Y = 256 - (3 * LINE_H + 2 * LINE_GAP) / 2
BLOCK_H = 3 * LINE_H + 2 * LINE_GAP

# (name, text, x, y, w) of each piece, relative to the block.
PIECES = [
    ("sale", "SALE", 0, 0, 1),
    ("lagi", "LAGI", 0, LINE_H + LINE_GAP, 1),
    ("hai", "HAI", 0, 2 * (LINE_H + LINE_GAP), 0.74),
    ("bang", "!", 0.82, 2 * (LINE_H + LINE_GAP), 0.18),
]


class DartPen(BasePen):
    """Collects outlines as flat [op, coords...] numbers for the splash."""

    def __init__(self, glyphs):
        super().__init__(glyphs)
        self.values = []

    def _add(self, op, *points):
        self.values.append(op)
        for x, y in points:
            self.values.extend((round(x, 1), round(y, 1)))

    def _moveTo(self, p):
        self._add(0, p)

    def _lineTo(self, p):
        self._add(1, p)

    def _qCurveToOne(self, c, p):
        self._add(2, c, p)

    def _curveToOne(self, c1, c2, p):
        self._add(3, c1, c2, p)

    def _closePath(self):
        self.values.append(4)


def fit(text, box, make_pen):
    """Shapes [text] and draws it filling box = (x, y, w, h)."""
    tt = TTFont(FONT)
    glyphs = tt.getGlyphSet()
    font = hb.Font(hb.Face(hb.Blob.from_file_path(str(FONT))))
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(font, buf)

    placed, cursor = [], 0
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        placed.append((tt.getGlyphName(info.codepoint), cursor + pos.x_offset))
        cursor += pos.x_advance

    bounds = BoundsPen(glyphs)
    for name, gx in placed:
        glyphs[name].draw(TransformPen(bounds, (1, 0, 0, 1, gx, 0)))
    x0, y0, x1, y1 = bounds.bounds

    bx, by, bw, bh = box
    sx, sy = bw / (x1 - x0), bh / (y1 - y0)
    pen = make_pen(glyphs)
    for name, gx in placed:
        matrix = (sx, 0, 0, -sy, bx + (gx - x0) * sx, by + y1 * sy)
        glyphs[name].draw(TransformPen(pen, matrix))
    return pen


def svg_pen(glyphs):
    return SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))


def block_path(scale=1.0, dx=BLOCK_X, dy=BLOCK_Y):
    """The whole block as one SVG path."""
    commands = []
    for _, text, px, py, pw in PIECES:
        box = (
            dx + px * BLOCK_W * scale,
            dy + py * scale,
            pw * BLOCK_W * scale,
            LINE_H * scale,
        )
        commands.append(fit(text, box, svg_pen).getCommands())
    return "".join(commands)


def vector(comment, size, fill, data):
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {comment} -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp" android:height="{size}dp"\n'
        f'    android:viewportWidth="{size}" android:viewportHeight="{size}">\n'
        f'    <path android:fillColor="{fill}" android:pathData="{data}"/>\n'
        "</vector>\n"
    )


def android_vectors():
    k = 72 / 512
    foreground = block_path(k, 18 + BLOCK_X * k, 18 + BLOCK_Y * k)
    (RES / "drawable/ic_launcher_foreground.xml").write_text(
        vector("Adaptive icon foreground. Generated by build_naam.py.",
               108, WHITE, foreground)
    )
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(
        vector("Themed icon (Android 13+). Generated by build_naam.py.",
               108, "#FF000000", foreground)
    )
    (RES / "drawable/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<shape xmlns:android="http://schemas.android.com/apk/res/android">\n'
        f'    <solid android:color="{RED}"/>\n'
        "</shape>\n"
    )
    # The full name is unreadable at 24dp, so the notification icon is its S.
    small = fit("S", (6.5, 2, 11, 20), svg_pen).getCommands()
    (RES / "drawable/ic_stat_sale.xml").write_text(
        vector("Notification small icon. White silhouette; system tints it.",
               24, "#FFFFFFFF", small)
    )


def svg(fill, ground=None, size=512):
    rect = f'<rect width="512" height="512" fill="{ground}"/>' if ground else ""
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" '
        f'height="{size}" viewBox="0 0 512 512">{rect}'
        f'<path fill="{fill}" d="{block_path()}"/></svg>'
    )


def raster(markup, size, work):
    """Renders SVG markup to a square RGB image with Chrome."""
    page = work / "page.html"
    shot = work / "shot.png"
    page.write_text(
        "<!doctype html><style>html,body{margin:0;background:#fff}"
        f"svg{{display:block;width:{size}px;height:{size}px}}</style>{markup}"
    )
    subprocess.run(
        [CHROME, "--headless=new", "--disable-gpu", "--hide-scrollbars",
         "--force-device-scale-factor=1", f"--window-size={size},{size}",
         f"--user-data-dir={work / 'chrome'}", f"--screenshot={shot}",
         f"file://{page}"],
        check=True, capture_output=True,
    )
    return Image.open(shot).convert("RGB").crop((0, 0, size, size))


def mask(size, shape):
    big = Image.new("L", (size * 4, size * 4), 0)
    draw = ImageDraw.Draw(big)
    box = (0, 0, size * 4 - 1, size * 4 - 1)
    if shape == "round":
        draw.ellipse(box, fill=255)
    else:
        draw.rounded_rectangle(box, radius=size * 4 * 0.2, fill=255)
    return big.resize((size, size), Image.LANCZOS)


def mipmaps(tile):
    for density, px in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96),
                        ("xxhdpi", 144), ("xxxhdpi", 192)):
        icon = tile.resize((px, px), Image.LANCZOS)
        for name, shape in (("ic_launcher", "square"),
                            ("ic_launcher_round", "round")):
            out = icon.convert("RGBA")
            out.putalpha(mask(px, shape))
            out.save(RES / f"mipmap-{density}/{name}.png", optimize=True)


def lockups(ink):
    """The welcome-screen logo: the bare block, red on light, white on dark."""
    assets = ROOT / "assets/brand"
    left, top = BLOCK_X * 4, int(BLOCK_Y * 4)
    width, height = BLOCK_W * 4, int(BLOCK_H * 4)
    shape = ink.crop((left, top, left + width, top + height)).convert("L")
    alpha = shape.point(lambda v: 255 - v)
    for theme, colour in (("light", RED), ("dark", WHITE)):
        solid = Image.new("RGBA", (width, height), colour)
        solid.putalpha(alpha)
        for folder, scale in ((assets, 1), (assets / "2.0x", 2),
                              (assets / "3.0x", 3)):
            canvas = Image.new("RGBA", (240 * scale, 174 * scale), (0, 0, 0, 0))
            high = 174 * scale
            wide = round(high * BLOCK_W / BLOCK_H)
            fitted = solid.resize((wide, high), Image.LANCZOS)
            canvas.paste(fitted, ((canvas.width - wide) // 2, 0))
            canvas.save(folder / f"lockup_{theme}.png", optimize=True)


def dart_outlines():
    """The block's pieces, in a 300 x 338 box, for the splash painter."""
    lines = [
        "// Generated by design/_src/build_naam.py. Do not edit.",
        "",
        "/// The logo's pieces as flat path data: an op, then its points.",
        "/// Ops: 0 move, 1 line, 2 quadratic, 3 cubic, 4 close.",
        f"const logoBlockWidth = {BLOCK_W}.0;",
        f"const logoBlockHeight = {BLOCK_H:.1f};",
        "",
    ]
    for name, text, px, py, pw in PIECES:
        box = (px * BLOCK_W, py, pw * BLOCK_W, LINE_H)
        values = fit(text, box, DartPen).values
        body = ", ".join(f"{v:g}" for v in values)
        lines.append(f"const logo{name.title()} = <double>[{body}];")
        lines.append("")
    path = ROOT / "lib/app/splash/logo_outlines.dart"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "symbol-tile.svg").write_text(svg(WHITE, RED))
    (OUT / "symbol-red.svg").write_text(svg(RED))
    (OUT / "symbol-white.svg").write_text(svg(WHITE))
    (OUT / "symbol-black.svg").write_text(svg("#000000"))

    android_vectors()
    dart_outlines()
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        tile = raster(svg(WHITE, RED, 1024), 1024, work)
        ink = raster(svg("#000000", "#FFFFFF", 2048), 2048, work)
    tile.resize((512, 512), Image.LANCZOS).save(OUT / "play-store-512.png")
    mipmaps(tile)
    lockups(ink)


if __name__ == "__main__":
    sys.exit(main())
